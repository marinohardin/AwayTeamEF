/* cfg_overlay: parsing, the cvar rule, and merging a mod session's changes into the main config */
#include "cfg_overlay.h"
#include "lc_test.h"
#include <stdlib.h>

#define L( s ) s, strlen( s )

static void TestParse( void )
{
	cfgovLine_t l;

	CHECK( CfgOv_ParseLine( L( "bind f \"+button3\"" ), &l ) == CFGOV_BIND );
	CHECK_STR( l.name, "f" );
	CHECK_STR( l.value, "+button3" );

	/* a quoted command with spaces and ';' stays one value */
	CHECK( CfgOv_ParseLine( L( "bind F1 \"vote yes; say hi\"\r\n" ), &l ) == CFGOV_BIND );
	CHECK_STR( l.name, "F1" );
	CHECK_STR( l.value, "vote yes; say hi" );

	/* unquoted: the rest of the line, joined by single spaces (as the engine's bind does) */
	CHECK( CfgOv_ParseLine( L( "  BIND x  say   hello there" ), &l ) == CFGOV_BIND );
	CHECK_STR( l.value, "say hello there" );

	CHECK( CfgOv_ParseLine( L( "bind x" ), &l ) == CFGOV_OTHER );	/* only prints the binding */

	CHECK( CfgOv_ParseLine( L( "seta r_highdpi \"1\"" ), &l ) == CFGOV_SET );
	CHECK( l.archive == 1 );
	CHECK_STR( l.name, "r_highdpi" );
	CHECK_STR( l.value, "1" );
	CHECK( CfgOv_ParseLine( L( "set name \"^1Red Shirt\"" ), &l ) == CFGOV_SET );
	CHECK( l.archive == 0 );
	CHECK_STR( l.value, "^1Red Shirt" );
	CHECK( CfgOv_ParseLine( L( "seta cg_empty \"\"" ), &l ) == CFGOV_SET );
	CHECK_STR( l.value, "" );

	CHECK( CfgOv_ParseLine( L( "unbindall" ), &l ) == CFGOV_UNBINDALL );
	CHECK( CfgOv_ParseLine( L( "// generated by quake, do not modify" ), &l ) == CFGOV_NONE );
	CHECK( CfgOv_ParseLine( L( "   " ), &l ) == CFGOV_NONE );
	CHECK( CfgOv_ParseLine( L( "" ), &l ) == CFGOV_NONE );
	CHECK( CfgOv_ParseLine( L( "vstr intro" ), &l ) == CFGOV_OTHER );
}

static void TestSetAction( void )
{
	/* registered by the engine (r_highdpi, sensitivity, name): the main config's value now */
	CHECK( CfgOv_SetAction( 1, 0, 0 ) == CFGOV_APPLY_NOW );
	/* registered by a game module (cg_, ui_ and mod cvars): the mod keeps its own */
	CHECK( CfgOv_SetAction( 1, 0, 1 ) == CFGOV_KEEP_MOD );
	/* only set by a config so far, or not at all: decided when someone registers it */
	CHECK( CfgOv_SetAction( 1, 1, 0 ) == CFGOV_APPLY_ON_REGISTER );
	CHECK( CfgOv_SetAction( 0, 0, 0 ) == CFGOV_APPLY_ON_REGISTER );
}

typedef struct {
	int binds, sets, others, unbindalls;
} counts_t;

static void Count( const cfgovLine_t *l, const char *raw, size_t rawLen, void *ctx )
{
	counts_t *c = ctx;
	(void)raw;
	(void)rawLen;
	if ( l->kind == CFGOV_BIND ) c->binds++;
	if ( l->kind == CFGOV_SET ) c->sets++;
	if ( l->kind == CFGOV_OTHER ) c->others++;
	if ( l->kind == CFGOV_UNBINDALL ) c->unbindalls++;
}

static void TestForEach( void )
{
	counts_t c = { 0, 0, 0, 0 };

	CfgOv_ForEachLine( "// x\r\nunbindall\nbind a \"+forward\"\n\nseta s \"1\"\r\nset t 2\nexec other.cfg", Count, &c );
	CHECK( c.unbindalls == 1 && c.binds == 1 && c.sets == 2 && c.others == 1 );
	CfgOv_ForEachLine( NULL, Count, &c );	/* no file: nothing */
	CHECK( c.binds == 1 );
}

static const char *base =
	"// generated by quake, do not modify\n"
	"unbindall\n"
	"bind f \"+button3\"\n"
	"bind g \"messagemode3\"\n"
	"bind h \"messagemode4\"\n"
	"bind w \"+forward\"\n"
	"seta r_highdpi \"0\"\n"
	"seta sensitivity \"5\"\n"
	"seta cg_drawFPS \"1\"\n"
	"set cl_temp \"x\"\n"
	"exec mine.cfg\n";

static void TestMergeNothingChanged( void )
{
	char *out = CfgOv_MergeBase( base, NULL, 0, NULL, 0 );

	CHECK_STR( out,
		"// generated by quake, do not modify\n"
		"unbindall\n"
		"bind f \"+button3\"\n"
		"bind g \"messagemode3\"\n"
		"bind h \"messagemode4\"\n"
		"bind w \"+forward\"\n"
		"seta r_highdpi \"0\"\n"
		"seta sensitivity \"5\"\n"
		"seta cg_drawFPS \"1\"\n"
		"set cl_temp \"x\"\n"
		"exec mine.cfg\n" );
	free( out );
}

static void TestMergeChanges( void )
{
	/* in a mod the player rebound h, unbound g, bound a new key, and turned Retina on */
	const cfgovBind_t changed[] = {
		{ "H", "+zoom" },			/* key names are case-insensitive */
		{ "g", "" },
		{ "MOUSE3", "+button2" },
		{ "k", "" },				/* unbound and never in the main config: nothing */
	};
	/* the engine cvars as they are now (game modules' cvars are never passed) */
	const cfgovCvar_t engine[] = {
		{ "R_HIGHDPI", "1" },
		{ "sensitivity", "5" },
		{ "s_volume", "0.4" },		/* not in the main config yet */
	};
	char *out = CfgOv_MergeBase( base, changed, 4, engine, 3 );

	CHECK_STR( out,
		"// generated by quake, do not modify\n"
		"unbindall\n"
		"bind f \"+button3\"\n"
		"bind h \"+zoom\"\n"
		"bind w \"+forward\"\n"
		"bind MOUSE3 \"+button2\"\n"
		"seta r_highdpi \"1\"\n"
		"seta sensitivity \"5\"\n"
		"seta cg_drawFPS \"1\"\n"			/* a game module's: the main config's stays */
		"set cl_temp \"x\"\n"
		"seta s_volume \"0.4\"\n"
		"exec mine.cfg\n" );
	free( out );
}

static void TestMergeNoBase( void )
{
	const cfgovBind_t changed[] = { { "f", "+button3" } };
	const cfgovCvar_t engine[] = { { "r_highdpi", "1" } };
	char *out = CfgOv_MergeBase( NULL, changed, 1, engine, 1 );

	CHECK_STR( out,
		"// generated by quake, do not modify\n"
		"unbindall\n"
		"bind f \"+button3\"\n"
		"seta r_highdpi \"1\"\n" );
	free( out );
}

static void TestMergeDuplicateKey( void )
{
	/* a hand-edited config binding the same key twice: the change replaces both */
	const cfgovBind_t changed[] = { { "f", "+use" } };
	char *out = CfgOv_MergeBase( "bind f \"a\"\nbind f \"b\"\n", changed, 1, NULL, 0 );

	CHECK_STR( out, "// generated by quake, do not modify\nunbindall\nbind f \"+use\"\n" );
	free( out );
}

static void TestMergeBig( void )
{
	/* more than the first buffer holds */
	char *big = malloc( 200000 ), *out;
	size_t len = 0;
	int i;

	for ( i = 0; i < 5000; i++ )
		len += (size_t)sprintf( big + len, "seta v%d \"%d\"\n", i, i );
	out = CfgOv_MergeBase( big, NULL, 0, NULL, 0 );
	CHECK( out != NULL );
	CHECK( out && strstr( out, "seta v4999 \"4999\"\n" ) != NULL );
	free( out );
	free( big );
}

int main( void )
{
	TestParse( );
	TestSetAction( );
	TestForEach( );
	TestMergeNothingChanged( );
	TestMergeChanges( );
	TestMergeNoBase( );
	TestMergeDuplicateKey( );
	TestMergeBig( );
	return TEST_DONE( );
}
